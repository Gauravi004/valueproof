/**
 * Returns the localized name of a town given its current value and translator function t.
 * If the location matches any known alias, it translates to the active locale town name.
 */
export function getLocalizedTownName(location: string, t: (key: string) => string): string {
  if (!location) return t('towns.alwar');
  const normalized = location.trim().toLowerCase();

  for (const town of KNOWN_TOWNS) {
    if (town.aliases.some((alias) => alias.toLowerCase() === normalized || normalized.includes(alias.toLowerCase()))) {
      return t(`towns.${town.key}`);
    }
  }

  return location;
}
